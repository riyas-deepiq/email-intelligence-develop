#!/usr/bin/env bash
# ============================================================================
# Per-machine configuration, run from the package's post-install script.
#
#   finalize-config.sh --role server
#   finalize-config.sh --role collector [--join-file PATH] [--skip-firewall]
#
# The Linux counterpart of installer/windows/scripts/finalize-config.ps1. Two
# things are deliberately different from the Windows side:
#
#   * No __INSTALLDIR__ resolution. FHS paths are fixed at build time, so there
#     is no prefix to substitute — the whole placeholder mechanism is gone.
#
#   * Nothing is written to .env. Generated values go to secrets.env, which the
#     unit loads with EnvironmentFile= and which therefore wins (dotenv does not
#     override variables already set in the environment). The .env files stay
#     byte-identical to what the package shipped, so dpkg never reports them as
#     locally modified and an upgrade never stops to ask about them.
#
# What it still does, unchanged in spirit:
#   1. Generates JWT_SECRET, OIDC_ENCRYPTION_KEY and COLLECTOR_SECRET so no two
#      installations share one.
#   2. Joins the server and the collector, whichever was installed second.
#   3. Opens the server's port. A collector listens on loopback only and gets no
#      firewall rule at all.
#
# Idempotent: re-running fills in only what is still unresolved and never
# rewrites an administrator's edits.
# ============================================================================
set -euo pipefail

CONF="/etc/insight-hub"
LOGDIR="/var/log/insight-hub"

ROLE="server"
SERVICE_USER="email-intel"
# Derived from CONF, not written out again: the two must never drift apart.
JOIN_FILE="${INSIGHT_HUB_JOIN_FILE:-$CONF/collector-join.env}"
SKIP_FIREWALL=0

while [ $# -gt 0 ]; do
    case "$1" in
        --role)          ROLE="${2:-}"; shift 2 ;;
        --user)          SERVICE_USER="${2:-}"; shift 2 ;;
        --join-file)     JOIN_FILE="${2:-}"; shift 2 ;;
        --skip-firewall) SKIP_FIREWALL=1; shift ;;
        *) echo "finalize-config.sh: unknown option $1" >&2; exit 2 ;;
    esac
done
[ "$ROLE" = "server" ] || [ "$ROLE" = "collector" ] || {
    echo "finalize-config.sh: --role must be 'server' or 'collector'" >&2; exit 2; }

mkdir -p "$LOGDIR"
LOG_FILE="$LOGDIR/install-config.log"
log() { printf '%s  %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*" | tee -a "$LOG_FILE"; }

# ── .env helpers ─────────────────────────────────────────────────────────────
# Values are written unquoted wherever that round-trips: dotenv expands \n inside
# double-quoted values, so a quoted path ending in \newdata would come back
# containing a newline.
env_get() {  # env_get <file> <key>
    [ -f "$1" ] || return 0
    sed -n -E "s/^[[:space:]]*$2[[:space:]]*=[[:space:]]*(.*)$/\1/p" "$1" | head -1 | sed -e 's/[[:space:]]*$//'
}

env_set() {  # env_set <file> <key> <value>
    local file="$1" key="$2" value="$3" tmp
    tmp="$(mktemp)"
    if grep -qE "^[[:space:]]*$key[[:space:]]*=" "$file" 2>/dev/null; then
        # awk, not sed: the value can contain & / \ and any other sed metacharacter.
        awk -v k="$key" -v v="$value" '
            $0 ~ "^[[:space:]]*"k"[[:space:]]*=" && !done { print k"="v; done=1; next }
            { print }
        ' "$file" >"$tmp"
    else
        cat "$file" >"$tmp" 2>/dev/null || true
        printf '%s=%s\n' "$key" "$value" >>"$tmp"
    fi
    cat "$tmp" >"$file"     # preserve the original inode, owner and mode
    rm -f "$tmp"
}

# The value the service will actually see: secrets.env (loaded by systemd) wins
# over .env (loaded by dotenv, which does not override).
eff_get() {  # eff_get <dir> <key>
    local dir="$1" key="$2" v
    v="$(env_get "$dir/secrets.env" "$key")"
    [ -n "$v" ] && { printf '%s' "$v"; return 0; }
    env_get "$dir/.env" "$key"
}

# Creates secrets.env with the right owner and mode before anything is written
# into it, so a secret is never briefly world-readable.
ensure_secrets_file() {  # ensure_secrets_file <dir>
    local f="$1/secrets.env"
    if [ ! -f "$f" ]; then
        ( umask 077; : >"$f" )
        cat >"$f" <<'EOF'
# Generated by the Insight Hub package at install time. NOT a package
# file: `apt purge` / manual removal deletes it, and reinstalling regenerates it.
#
# Loaded by the systemd unit with EnvironmentFile=, so everything here overrides
# the matching key in .env. Edit freely — this file is never rewritten once a
# value is present.
EOF
    fi
    chown "root:$SERVICE_USER" "$f" 2>/dev/null || true
    chmod 0640 "$f"
}

# 48 random bytes as base64url — 64 URL-safe characters, no padding.
new_secret() {
    if command -v openssl >/dev/null 2>&1; then
        openssl rand -base64 48 | tr '+/' '-_' | tr -d '=\n'
    else
        head -c 48 /dev/urandom | base64 | tr '+/' '-_' | tr -d '=\n'
    fi
}

# 64 lowercase hex characters — the AES-256-GCM key format the server validates.
new_hexkey() {
    if command -v openssl >/dev/null 2>&1; then
        openssl rand -hex 32
    else
        od -An -tx1 -N32 /dev/urandom | tr -d ' \n'
    fi
}

# Writes one collector instance's secrets.env and restarts it if the secret changed.
update_collector_instance() {  # <config-dir> <secret> <server-url>
    local dir="$1" secret="$2" server_url="$3"
    local instance current before after
    [ -f "$dir/.env" ] || return 0

    instance="$(basename "$dir")"; instance="${instance#collector}"
    ensure_secrets_file "$dir"

    before="$(eff_get "$dir" COLLECTOR_SECRET)"
    current="$(eff_get "$dir" SERVER_URL)"

    # This collector belongs to a server on another machine: leave its
    # credentials entirely alone. Installing a server here does not make us its
    # owner, and overwriting the secret while keeping the remote URL would aim it
    # at a different server holding a credential that server has never seen.
    local loopback='^https?://(127\.0\.0\.1|localhost)(:[0-9]+)?/?$'
    if [ -n "$server_url" ] && [[ "$server_url" =~ $loopback ]] \
       && [ -n "$current" ] && ! [[ "$current" =~ $loopback ]]; then
        log "collector$instance: left as-is - it is configured against $current, not this machine."
        return 0
    fi

    [ -n "$secret" ]     && env_set "$dir/secrets.env" COLLECTOR_SECRET "$secret"
    [ -n "$server_url" ] && env_set "$dir/secrets.env" SERVER_URL "$server_url"

    after="$(eff_get "$dir" COLLECTOR_SECRET)"
    if [ -z "$after" ] || [ "$after" = "CHANGE_ME" ]; then
        log "collector$instance: written, but COLLECTOR_SECRET is UNSET - set SERVER_URL and COLLECTOR_SECRET in $dir/secrets.env, then restart."
        return 0
    fi

    log "Collector configuration written: collector$instance"
    [ "$before" = "$after" ] && return 0

    local unit="insight-hub-collector@$instance"
    if systemctl is-active --quiet "$unit" 2>/dev/null; then
        systemctl restart "$unit" && log "$unit restarted to pick up the new secret." \
            || log "$unit could not be restarted - run: systemctl restart $unit"
    fi
}

log "Preparing configuration (role: $ROLE)"

if [ "$ROLE" = "server" ]; then

    SERVER_DIR="$CONF/server"
    [ -f "$SERVER_DIR/.env" ] || { log "ERROR: $SERVER_DIR/.env not found"; exit 1; }
    ensure_secrets_file "$SERVER_DIR"

    generated=""
    for key in JWT_SECRET OIDC_ENCRYPTION_KEY COLLECTOR_SECRET; do
        current="$(eff_get "$SERVER_DIR" "$key")"
        if [ -z "$current" ] || [ "$current" = "CHANGE_ME" ]; then
            if [ "$key" = "OIDC_ENCRYPTION_KEY" ]; then value="$(new_hexkey)"; else value="$(new_secret)"; fi
            env_set "$SERVER_DIR/secrets.env" "$key" "$value"
            generated="$generated $key"
        fi
    done
    if [ -n "$generated" ]; then
        log "Generated per-machine secrets:$generated"
    else
        log "Secrets already present; none generated."
    fi

    SECRET="$(eff_get "$SERVER_DIR" COLLECTOR_SECRET)"
    PORT="$(eff_get "$SERVER_DIR" PORT)"; PORT="${PORT:-8080}"

    found=0
    for dir in "$CONF"/collector*/; do
        [ -d "$dir" ] && [ -f "${dir}.env" ] || continue
        found=1
        update_collector_instance "${dir%/}" "$SECRET" "http://127.0.0.1:$PORT"
    done
    [ "$found" -eq 0 ] && log "No collector installation on this machine."

    if [ "$SKIP_FIREWALL" -eq 0 ]; then
        if command -v firewall-cmd >/dev/null 2>&1 && firewall-cmd --state >/dev/null 2>&1; then
            firewall-cmd --permanent --add-port="$PORT/tcp" >/dev/null 2>&1 || true
            firewall-cmd --reload >/dev/null 2>&1 || true
            log "firewalld: opened $PORT/tcp."
        elif command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q '^Status: active'; then
            ufw allow "$PORT/tcp" >/dev/null 2>&1 || true
            log "ufw: opened $PORT/tcp."
        else
            log "No active firewalld or ufw - nothing to open."
        fi
    fi

else

    # Preference order for the secret: a server installed on this machine, then a
    # join file, then nothing. It is never generated — it has to match the
    # server's exactly, and a fabricated value produces a collector that polls,
    # is rejected, and looks healthy.
    SECRET=""
    SERVER_URL=""

    if [ -f "$CONF/server/.env" ]; then
        SECRET="$(eff_get "$CONF/server" COLLECTOR_SECRET)"
        SPORT="$(eff_get "$CONF/server" PORT)"; SPORT="${SPORT:-8080}"
        SERVER_URL="http://127.0.0.1:$SPORT"
        log "Server package found on this machine - adopting its secret and port."
    fi

    if [ -z "$SECRET" ] && [ -n "$JOIN_FILE" ] && [ -f "$JOIN_FILE" ]; then
        SECRET="$(env_get "$JOIN_FILE" COLLECTOR_SECRET)"
        JURL="$(env_get "$JOIN_FILE" SERVER_URL)"
        [ -n "$JURL" ] && SERVER_URL="$JURL"
        log "Join file applied: $JOIN_FILE"
    fi

    [ -z "$SECRET" ] && log "No local server and no usable join file - this collector must be configured by hand."

    for dir in "$CONF"/collector*/; do
        [ -d "$dir" ] && [ -f "${dir}.env" ] || continue
        update_collector_instance "${dir%/}" "$SECRET" "$SERVER_URL"
    done
fi

# Re-assert ownership: files were just written, and the package may have
# restored .env modes on upgrade.
chown -R "root:$SERVICE_USER" "$CONF" 2>/dev/null || true
chmod 0750 "$CONF" 2>/dev/null || true
find "$CONF" -name '.env'        -exec chmod 0640 {} + 2>/dev/null || true
find "$CONF" -name 'secrets.env' -exec chmod 0640 {} + 2>/dev/null || true
# The client file is served to the browser and holds nothing secret.
[ -f "$CONF/client/.env" ] && chmod 0644 "$CONF/client/.env" 2>/dev/null || true

log "Configuration complete."
