#!/usr/bin/env bash
# ============================================================================
# Adds another collector instance.
#
#   sudo /usr/lib/insight-hub/collector/add-collector.sh 2
#   sudo /usr/lib/insight-hub/collector/add-collector.sh 3 --concurrency 5
#
# Each instance needs its own configuration directory and its own port. There is
# no new unit file to create: the packaged unit is a systemd *template*, so
# instance N simply *is* insight-hub-collector@N, reading
# /etc/insight-hub/collectorN/.
#
# Instances created here are NOT owned by the package. They survive upgrades
# untouched, and the package's post-removal script disables every one of them.
# ============================================================================
set -euo pipefail

CONF="/etc/insight-hub"
SERVICE_USER="email-intel"

INSTANCE=""
PORT=""
CONCURRENCY=""

usage() { echo "usage: sudo $0 <instance 2-99> [--port N] [--concurrency N]" >&2; }

while [ $# -gt 0 ]; do
    case "$1" in
        --port)        PORT="${2:-}"; shift 2 ;;
        --concurrency) CONCURRENCY="${2:-}"; shift 2 ;;
        -h|--help)     usage; exit 0 ;;
        *)             INSTANCE="$1"; shift ;;
    esac
done

[ -n "$INSTANCE" ] || { usage; exit 2; }
case "$INSTANCE" in ''|*[!0-9]*) usage; exit 2 ;; esac
[ "$INSTANCE" -ge 2 ] && [ "$INSTANCE" -le 99 ] || {
    echo "Instance must be between 2 and 99. Instance 1 belongs to the package." >&2; exit 2; }

[ "$(id -u)" -eq 0 ] || { echo "Run as root — this enables a systemd unit." >&2; exit 1; }

SRC_DIR="$CONF/collector1"
TARGET_DIR="$CONF/collector$INSTANCE"
UNIT="insight-hub-collector@$INSTANCE"

[ -f "$SRC_DIR/.env" ] || { echo "Collector 1 configuration not found at $SRC_DIR/.env" >&2; exit 1; }
[ -x /usr/bin/insight-hub-collector ] || { echo "The collector binary is not installed." >&2; exit 1; }
systemctl cat insight-hub-collector@.service >/dev/null 2>&1 || {
    echo "The collector template unit is not installed." >&2; exit 1; }
[ -d "$TARGET_DIR" ] && { echo "$TARGET_DIR already exists. Remove that instance first, or pick another number." >&2; exit 1; }

PORT="${PORT:-$((3000 + INSTANCE))}"

# Surface a port clash here rather than as a unit that starts and dies.
if command -v ss >/dev/null 2>&1 && ss -ltn "( sport = :$PORT )" 2>/dev/null | grep -q ":$PORT"; then
    echo "Port $PORT is already in use. Pass --port to choose another." >&2; exit 1
fi

get() {  # get <file> <key>
    [ -f "$1" ] || return 0
    sed -n -E "s/^[[:space:]]*$2[[:space:]]*=[[:space:]]*(.*)$/\1/p" "$1" | head -1 | sed -e 's/[[:space:]]*$//'
}
# secrets.env wins over .env, exactly as systemd + dotenv resolve it at runtime.
eff() { local v; v="$(get "$SRC_DIR/secrets.env" "$1")"; [ -n "$v" ] && printf '%s' "$v" || get "$SRC_DIR/.env" "$1"; }

SECRET="$(eff COLLECTOR_SECRET)"
SERVER_URL="$(eff SERVER_URL)"

[ -n "$SECRET" ] && [ "$SECRET" != "CHANGE_ME" ] || {
    echo "Collector 1 has no usable COLLECTOR_SECRET — configure instance 1 first." >&2; exit 1; }

mkdir -p "$TARGET_DIR"

# COLLECTOR_INSTANCE_ID is deliberately blanked, not copied: it defaults to
# <hostname>:<PORT>, and inheriting instance 1's value would give two collectors
# the same identity — they would overwrite each other's heartbeat and appear as
# one flickering entry.
sed -e "s|^[[:space:]]*PORT[[:space:]]*=.*|PORT=$PORT|" \
    -e "s|^[[:space:]]*COLLECTOR_INSTANCE_ID[[:space:]]*=.*|COLLECTOR_INSTANCE_ID=|" \
    "$SRC_DIR/.env" >"$TARGET_DIR/.env"

if [ -n "$CONCURRENCY" ]; then
    sed -i -e "s|^[[:space:]]*WORKER_CONCURRENCY[[:space:]]*=.*|WORKER_CONCURRENCY=$CONCURRENCY|" "$TARGET_DIR/.env"
fi

# Written with umask 077 first so the secret is never briefly world-readable.
( umask 077; cat >"$TARGET_DIR/secrets.env" <<EOF
# Generated by add-collector.sh for instance $INSTANCE. Not a package file.
COLLECTOR_SECRET=$SECRET
SERVER_URL=$SERVER_URL
EOF
)

chown -R "root:$SERVICE_USER" "$TARGET_DIR"
chmod 0750 "$TARGET_DIR"
chmod 0640 "$TARGET_DIR/.env" "$TARGET_DIR/secrets.env"
echo "Configuration written: $TARGET_DIR (port $PORT)"

systemctl enable --now "$UNIT"
echo "Enabled and started $UNIT"

# lastPollOk is the real proof: it is false when the shared secret is wrong.
sleep 5
if command -v curl >/dev/null 2>&1; then
    if health="$(curl -fsS --max-time 10 "http://127.0.0.1:$PORT/health" 2>/dev/null)"; then
        echo "Health: $health"
        case "$health" in
            *'"lastPollOk":false'*) echo "WARNING: the collector cannot reach the server — check SERVER_URL and COLLECTOR_SECRET." >&2 ;;
        esac
    else
        echo "Health endpoint not answering yet — journalctl -u $UNIT -n 50 --no-pager" >&2
    fi
fi
